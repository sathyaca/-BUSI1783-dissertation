analyzer = SentimentIntensityAnalyzer()

def get_vader_sentiment(text):

    scores = analyzer.polarity_scores(str(text))
    compound = scores["compound"]

    if compound >= 0.05:
        label = "Positive"

    elif compound <= -0.05:
        label = "Negative"

    else:
        label = "Neutral"

    return label, compound


