# CELL 15 — CORRECTED SUSTAINABILITY TERM ANALYSIS
# ============================================================
#
# CORRECTION:
# 1. Uses word boundaries
# 2. Allows legitimate morphological variants
# 3. "eco" must appear as a standalone word
# 4. Prevents recommend, second, become, economy etc.
#    from being falsely counted as "eco"
#
# ============================================================

print("=== CORRECTED SUSTAINABILITY TERM FREQUENCY ===")

stem_terms = {

    "sustainab":
        r"\bsustainab\w*",

    "ethic":
        r"\bethic\w*",

    "eco":
        r"\beco\b",

    "organic":
        r"\borganic\w*",

    "recycl":
        r"\brecycl\w*",

    "greenwash":
        r"\bgreenwash\w*",

    "environment":
        r"\benvironment\w*",

    "carbon":
        r"\bcarbon\w*",

    "fair trade":
        r"\bfair\s+trade\b",

    "climate":
        r"\bclimate\w*",

    "renewable":
        r"\brenewable\w*",

    "conscious":
        r"\bconscious\w*",

    "vegan":
        r"\bvegan\w*"
}


text_lower = (
    df["Text"]
    .fillna("")
    .astype(str)
    .str.lower()
)


term_rows = []


for label, pattern in stem_terms.items():

    mask = text_lower.str.contains(
        pattern,
        regex=True,
        na=False
    )

    count = int(mask.sum())

    percentage = round(
        count / len(df) * 100,
        1
    )

    term_rows.append(
        [label, count, percentage]
    )

    print(
        f"{label}: "
        f"{count} reviews "
        f"({percentage}%)"
    )

